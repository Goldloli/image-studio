#!/usr/bin/env python3
"""Build an isolated React/Tauri source copy using cached offline dependencies."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import tempfile
import time

root = Path(__file__).resolve().parent.parent
parser=argparse.ArgumentParser()
parser.add_argument('--report-prefix',choices=['cherry','first-generation'],default='cherry')
prefix=parser.parse_args().report_prefix
sources = ["Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "apps", "crates", "tools", "resources"]
ignored = ["__pycache__", ".DS_Store", "node_modules", "dist", "gen", "autogenerated", "build", "*.egg-info"]
destination = root / f"verification/{prefix}-clean-source-build.json"
log_path = root / f"verification/{prefix}-clean-source-build.log"
destination.parent.mkdir(parents=True, exist_ok=True)


def source_inventory(directory):
    """Call before dependency installation/build, so only copied source is hashed."""
    return {
        str(path.relative_to(directory)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(directory.rglob("*")) if path.is_file()
    }


def output_text(value):
    return value.decode(errors="replace") if isinstance(value, bytes) else value or ""


with tempfile.TemporaryDirectory(prefix="image-studio-cherry-clean-") as temporary:
    clean = Path(temporary)
    for name in sources:
        source = root / name
        if source.is_dir():
            shutil.copytree(source, clean / name, ignore=shutil.ignore_patterns(*ignored))
        else:
            shutil.copy2(source, clean / name)
    # npm ci and Tauri generate node_modules/dist/permissions/gen after this point.
    inventory = source_inventory(clean)
    environment = os.environ.copy()
    environment["CARGO_TARGET_DIR"] = str(root / "target/clean-validation")
    environment["CARGO_NET_OFFLINE"] = "true"
    environment["npm_config_offline"] = "true"
    steps = [
        ("frontend-install", ["npm", "ci", "--offline", "--no-audit", "--no-fund"], clean / "apps/frontend"),
        ("frontend-build", ["npm", "run", "build"], clean / "apps/frontend"),
        ("native-build", ["cargo", "build", "--workspace", "--locked", "--offline"], clean),
    ]
    results = []
    exit_code = 0
    with log_path.open("w") as log:
        for name, command, directory in steps:
            started = time.monotonic()
            log.write(f"\n[{name}] cwd={directory.relative_to(clean)} command={command}\n")
            log.flush()
            try:
                result = subprocess.run(
                    command, cwd=directory, env=environment, capture_output=True, text=True, timeout=600
                )
                exit_code = result.returncode
                log.write(result.stdout + result.stderr)
            except subprocess.TimeoutExpired as error:
                exit_code = 124
                log.write(output_text(error.stdout) + output_text(error.stderr))
                log.write("\nStage exceeded its 600 second timeout.\n")
            except OSError as error:
                exit_code = 127
                log.write(f"{type(error).__name__}: {error}\n")
            results.append({
                "name": name,
                "command": command,
                "cwd": str(directory.relative_to(clean)),
                "exit_code": exit_code,
                "elapsed_seconds": round(time.monotonic() - started, 3),
            })
            log.flush()
            if exit_code:
                break
    report = {
        "method": "isolated source copy, not a Git checkout or commit",
        "declared_source_roots": sources,
        "commands": results,
        "exit_code": exit_code,
        "isolated_build_artifacts": "target/clean-validation",
        "build_cache": "Existing target/clean-validation and global npm/Cargo caches are reused; not a cold build.",
        "offline_mode": "npm --offline/npm_config_offline and Cargo --offline/CARGO_NET_OFFLINE; no OS network-denial claim.",
        "source_inventory_timing": "after copy, before npm ci, frontend build or Cargo build",
        "source_files_sha256": inventory,
        "ignored_generated_names": ignored,
        "excluded": ["user data", "models", "Python inference environments", ".beads", ".codegraph", "node_modules", "dist", "gen", "permissions/autogenerated"],
        "log": str(log_path.relative_to(root)),
    }
    # A source edit during validation does not invalidate the copied build, but
    # must be visible so callers do not mistake it for verification of newer code.
    report["workspace_sources_changed_since_copy"] = [
        name for name, digest in inventory.items()
        if not (root / name).is_file() or hashlib.sha256((root / name).read_bytes()).hexdigest() != digest
    ]
    destination.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(destination)
    raise SystemExit(exit_code)
